_WEBHOOK_AVAILABLE = re.compile(
    r"(?m)^(?P<indent>[ \t]*)- versionName: (?P<base>projects/\$PROJECT_ID/secrets/)slack-webhook-workspace-orbit"
    r'/versions/latest\n(?P=indent)  env: "WEBHOOK_ORBIT"\n'
)


def with_people_secret(text: str) -> str:
    """A build that also gets the people map from Secret Manager: every step that can post to
    Slack (secretEnv WEBHOOK_ORBIT) gets RELEASE_PEOPLE_JSON, and availableSecrets names it."""
    if PEOPLE_ENV in text:
        return text
    text = _WEBHOOK_SECRET_ENV.sub(lambda m: f'{m["lead"]}, "{PEOPLE_ENV}"{m["end"]}', text)
    return _WEBHOOK_AVAILABLE.sub(
        lambda m: (
            m[0]
            + f"{m['indent']}- versionName: {m['base']}{PEOPLE_SECRET}/versions/latest\n"
            + f'{m["indent"]}  env: "{PEOPLE_ENV}"\n'
        ),
        text,
    )


def rendered(service: object) -> dict[str, str]:
    """The generated build files of one service: published path -> text.

    Without a vendored people map (a public repository) the builds read it from Secret Manager."""
    texts = _rendered(service)
    if people_vendored():
        return texts
    return {path: with_people_secret(text) for path, text in texts.items()}


def _rendered(service: object) -> dict[str, str]:
    """The generated build files of one service, before the people-map secret is added."""
    if getattr(service, "kind", "gke") == "vercel":
        return rendered_vercel(service)
    if getattr(service, "kind", "gke") == "railway":
        import release_railway  # noqa: PLC0415 - only kind railway needs it

        return release_railway.rendered(service)
    if getattr(service, "kind", "gke") == "static_site":
        import release_static  # noqa: PLC0415 - only kind static_site needs it

        return release_static.rendered(service)
    if getattr(service, "kind", "gke") != "gke" and not isinstance(service, rc.Service):
        light = {
            "service": service.name,  # type: ignore[attr-defined]
            "kind": service.kind,  # type: ignore[attr-defined]
            "project": service.project,  # type: ignore[attr-defined]
            "build_service_account": service.build_service_account,  # type: ignore[attr-defined]
            "checkpoints": " ".join(str(value) for value in service.checkpoints),  # type: ignore[attr-defined]
            "composer_note": ", the Airflow API" if service.kind == "composer" else "",  # type: ignore[attr-defined]
        }
        if not service.has_gate:  # type: ignore[attr-defined]
            return {service.window_config: LIGHT_WINDOW_TEMPLATE.format(**light)}  # type: ignore[attr-defined]
        light["rollback_trigger"] = service.rollback_trigger  # type: ignore[attr-defined]
        light["what"] = (
            "the traffic goes back to the target release's revisions"
            if service.kind == "cloud_run"  # type: ignore[attr-defined]
            else "the target commit's candidate folder goes to dags/"
        )
        return {
            service.window_config: LIGHT_FULL_WINDOW_TEMPLATE.format(**light),  # type: ignore[attr-defined]
            service.rollback_config: LIGHT_ROLLBACK_TEMPLATE.format(**light),  # type: ignore[attr-defined]
        }
    values = {
        "service": service.name,
        "rollback_trigger": service.rollback_trigger,
        "cluster": service.prod.cluster,
        "region": service.region,
        "project": service.project,
        "store": service.store,
        "checkpoints": " ".join(str(value) for value in service.checkpoints),
    }
    return {
        service.rollback_config: ROLLBACK_TEMPLATE.format(**values),
        service.window_config: WINDOW_TEMPLATE.format(**values),
    }


