"""The release kit in this repository: check that it is the shared copy, and render the build files.

The kit's source is orbit-infrastructure/release-kit/release/. Every repository
that uses it keeps a byte-identical copy in release/ (KIT.json pins the hash of
each file) plus its own service configs in release/services/<service>.json.
Change the kit only in orbit-infrastructure, then sync it:

    python3 release-kit/sync.py ../<repo>          # in orbit-infrastructure

In a repository that uses the kit:

    python3 release/release_kit.py check     # CI: the copy is unchanged, the configs load, the files are rendered
    python3 release/release_kit.py render    # write release/services/<service>.{rollback,release-verify}.yaml

Stdlib only.
"""

