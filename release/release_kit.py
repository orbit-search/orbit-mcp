def load_config(path: Path) -> object:
    """The service of a config file: a GKE Service, or a release_light.py service."""
    return rc.load_any_service(path.stem)


def digest(path: Path) -> str:
    """The sha256 hex digest of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rendered(service: object) -> dict[str, str]:
    """The generated build files of one service: published path -> text."""
    if getattr(service, "kind", "gke") != "gke" and not isinstance(service, rc.Service):
        light = {
            "service": service.name,  # type: ignore[attr-defined]
            "kind": service.kind,  # type: ignore[attr-defined]
            "project": service.project,  # type: ignore[attr-defined]
            "checkpoints": " ".join(str(value) for value in service.checkpoints),  # type: ignore[attr-defined]
            "composer_note": ", the Airflow API" if service.kind == "composer" else "",  # type: ignore[attr-defined]
        }
        if not service.has_gate:  # type: ignore[attr-defined]
            return {service.window_config: LIGHT_WINDOW_TEMPLATE.format(**light)}  # type: ignore[attr-defined]
        light["rollback_trigger"] = service.rollback_trigger  # type: ignore[attr-defined]
        light["what"] = (
            "the traffic goes back to the target release's revisions"
            if service.kind == "cloud_run"  # type: ignore[attr-defined]
            else "the target commit's candidate folder goes to dags/"
        )
        return {
            service.window_config: LIGHT_FULL_WINDOW_TEMPLATE.format(**light),  # type: ignore[attr-defined]
            service.rollback_config: LIGHT_ROLLBACK_TEMPLATE.format(**light),  # type: ignore[attr-defined]
        }
    values = {
        "service": service.name,
        "rollback_trigger": service.rollback_trigger,
        "cluster": service.prod.cluster,
        "region": service.region,
        "project": service.project,
        "store": service.store,
        "checkpoints": " ".join(str(value) for value in service.checkpoints),
    }
    return {
        service.rollback_config: ROLLBACK_TEMPLATE.format(**values),
        service.window_config: WINDOW_TEMPLATE.format(**values),
    }


def manifest_now() -> dict[str, str]:
    """The digest of every kit file as it is now: file name -> sha256."""
    return {name: digest(KIT_DIR / name) for name in KIT_FILES}


def cmd_check(_: argparse.Namespace) -> int:
    """Check that the kit files match KIT.json, the configs load and the build files are rendered; 1 on a problem."""
    problems = []
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        print(f"release kit: cannot read {MANIFEST}: {error}", file=sys.stderr)
        return 1
    pinned = manifest.get("files") or {}
    for name in KIT_FILES:
        path = KIT_DIR / name
        if not path.exists():
            problems.append(f"release/{name} is missing")
        elif pinned.get(name) != digest(path):
            problems.append(
                f"release/{name} differs from the shared kit {manifest.get('version')}; change it in "
                "orbit-infrastructure/release-kit and sync"
            )
    extra = sorted(set(pinned) - set(KIT_FILES))
    if extra:
        problems.append(f"KIT.json pins files this kit does not have: {', '.join(extra)}")
    files = rc.service_files()
    if not files:
        problems.append(f"no service config in {rc.SERVICES_DIR}")
    root = KIT_DIR.parent
    for path in files:
        try:
            service = load_config(path)
        except (rc.ConfigError, ValueError) as error:
            problems.append(str(error))
            continue
        for relative, text in rendered(service).items():
            target = root / relative
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                problems.append(
                    f"{relative} is not rendered from {path.name}; run python3 release/release_kit.py render"
                )
    for problem in problems:
        print(f"release kit: {problem}", file=sys.stderr)
    if not problems:
        print(f"release kit {manifest.get('version')}: {len(KIT_FILES)} files unchanged, {len(files)} service(s) OK")
    return 1 if problems else 0


def cmd_render(_: argparse.Namespace) -> int:
    """Write the generated build files of every service config."""
    root = KIT_DIR.parent
    for path in rc.service_files():
        service = load_config(path)
        for relative, text in rendered(service).items():
            (root / relative).write_text(text, encoding="utf-8")
            print(f"wrote {relative}")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Parse the command line and run check or render; return the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="the copy is the shared kit, the configs load, the build files are rendered")
    commands.add_parser("render", help="write the generated build files of every service")
    args = parser.parse_args(argv)
    try:
        return {"check": cmd_check, "render": cmd_render}[args.command](args)
    except rc.ConfigError as error:
        print(f"release kit: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
